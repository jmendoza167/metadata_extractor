def is_sensitive_name(name: str) -> bool:
    """Sensitive if it identifies a person, device or software, or is a date/time."""
    return (
        name in SENSITIVE_NAMES
        or name.startswith("XP")
        or "DateTime" in name
        or name.startswith(("OffsetTime", "SubSecTime"))
    )


